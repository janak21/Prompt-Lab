import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage();
const logs=[];
p.on('console',m=>logs.push(`[${m.type()}] ${m.text().slice(0,400)}`));
p.on('pageerror',e=>logs.push(`[PAGEERROR] ${String(e.stack||e).slice(0,900)}`));
p.on('requestfailed',r=>logs.push(`[REQFAIL] ${r.url().slice(0,140)} :: ${r.failure()?.errorText}`));
await p.goto('http://localhost:5173/prompts',{waitUntil:'networkidle'});
await p.waitForTimeout(2000);
console.log('#root children:', await p.evaluate(()=>document.getElementById('root')?.childElementCount));
console.log('#root html:', (await p.evaluate(()=>document.getElementById('root')?.innerHTML||'')).slice(0,400) || '(EMPTY)');
console.log('\n--- ALL LOGS ---\n'+(logs.join('\n')||'(none)'));
await b.close();
